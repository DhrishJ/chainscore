"""Write lib/site/plates.ts from the export metadata in web/*.json."""
import json, glob, os, sys

ALTS = {
    'calibre-hero': 'The ChainScore calibre from the caseback side: striped bridges, blued screws, '
                    'jewels in gold settings, and the balance wheel at lower right.',
    'calibre-escapement': 'Close view of the balance wheel, its hairspring and the shock-protected jewel '
                          'on the balance cock, with the train bridge behind.',
    'calibre-plan': 'The calibre seen from directly above.',
    'calibre-keyless': 'Detail of the keyless works: the snailed ratchet and crown wheels under blued screws, '
                       'with the click that stops the mainspring running back.',
}

web = sys.argv[1]
out = sys.argv[2]
rows = []
for f in sorted(glob.glob(os.path.join(web, '*.json'))):
    name = os.path.basename(f)[:-5]
    m = json.load(open(f))
    rows.append((name, m))

lines = [
    "// Generated by the calibre export script from the Blender renders.",
    "// Widths are the files present in public/calibre (largest first).",
    "",
    "export interface PlateInfo {",
    "  w: number",
    "  h: number",
    "  widths: number[]",
    "  alt: string",
    "  placeholder: string",
    "}",
    "",
    "export const PLATES = {",
]
for name, m in rows:
    widths = sorted(m['sizes'], reverse=True)
    lines.append(f"  '{name}': {{")
    lines.append(f"    w: {m['w']},")
    lines.append(f"    h: {m['h']},")
    lines.append(f"    widths: {json.dumps(widths)},")
    lines.append(f"    alt: {json.dumps(ALTS.get(name, ''))},")
    lines.append(f"    placeholder: '{m['placeholder']}',")
    lines.append("  },")
lines.append("} satisfies Record<string, PlateInfo>")
lines.append("")
lines.append("export type PlateName = keyof typeof PLATES")
lines.append("")
lines.append("/** Frames in public/calibre/explode/{d,m}: the scroll-driven explode. */")
lines.append(f"export const EXPLODE_FRAMES = {int(sys.argv[3]) if len(sys.argv) > 3 else 48}")
lines.append("")
open(out, 'w').write('\n'.join(lines))
print('wrote', out, [r[0] for r in rows])
